import { test, expect } from '@playwright/test';
import { defaults, modelSolar, npv, irr, annualLoan } from '../src/lib/solar';

test('energy and cash flows honour demand, roof, export and zero cases',()=>{
  const p={...defaults,monthlyKwh:100,roof:20,yield:1200,shade:0,selfUse:100,costPerKw:50000,tariff:10,om:1,degradation:0};
  const r=modelSolar(p);
  expect(r.capacity).toBe(1); expect(r.generation).toBe(1200); expect(r.net).toBe(11500);
  expect(r.cost).toBe(50000); expect(r.payback).toBeCloseTo(50000/11500);
  expect(modelSolar({...p,roof:0}).generation).toBe(0);
  expect(modelSolar({...p,roof:0}).payback).toBeNull();
  expect(modelSolar({...p,monthlyKwh:0}).irr).toBeNull();
  const oversized=modelSolar({...p,capacity:10,roof:100,selfUse:100});
  expect(oversized.rows[0].used).toBe(1200); expect(oversized.rows[0].exported).toBe(10800);
  const exporting=modelSolar({...p,selfUse:0,exportRate:3}); expect(exporting.net).toBe(3100);
  expect(()=>modelSolar({...p,yield:NaN})).toThrow();
});
test('investment formulas handle negative returns and zero-interest finance',()=>{
  expect(npv([-100,110],.1)).toBeCloseTo(0);
  expect(irr([-100,110])).toBeCloseTo(.1);
  expect(irr([-100,50])).toBeCloseTo(-.5);
  expect(irr([-100,-20])).toBeNull();
  expect(annualLoan(100000,0,5)).toBe(20000);
  expect(annualLoan(100000,12,1)).toBeCloseTo(106618.55,0);
});
